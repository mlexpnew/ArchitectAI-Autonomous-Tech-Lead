class VCSManager:
    """Manages local Git staging, remote repository creation, and Pull Request generation."""

    def __init__(self, project_dir: Path):
        self.project_dir = Path(project_dir).resolve()

    def _run_git(self, args: List[str], cwd: Optional[Path] = None) -> subprocess.CompletedProcess:
        """Helper to run git commands with proper working directory and error capture."""
        target_cwd = cwd or self.project_dir
        cmd = ["git"] + args
        return subprocess.run(
            cmd,
            cwd=str(target_cwd),
            capture_output=True,
            text=True,
            timeout=60,
        )

    def prepare_local_repository(
        self,
        project_name: str,
        branch_name: str = "feat/architectai-scaffold",
    ) -> Dict[str, Any]:
        """
        Initializes git in the project directory, stages all files,
        and creates structured semantic commits.
        """
        git_dir = self.project_dir / ".git"
        is_new_repo = not git_dir.exists()

        if is_new_repo:
            res_init = self._run_git(["init"])
            if res_init.returncode != 0:
                return {"success": False, "error": f"git init failed: {res_init.stderr}"}

        # Configure local git user if not present
        self._run_git(["config", "user.name", "ArchitectAI Bot"])
        self._run_git(["config", "user.email", "bot@architectai.dev"])

        # Stage and commit initial baseline if empty
        self._run_git(["checkout", "-B", "main"])
        self._run_git(["add", "."])
        
        # Check if there are changes to commit
        status_res = self._run_git(["status", "--porcelain"])
        if status_res.stdout.strip():
            commit_res = self._run_git([
                "commit",
                "-m",
                f"feat(arch): autonomous system scaffold for {project_name}\n\n"
                f"Generated by ArchitectAI Autonomous Tech Lead.",
            ])
            if commit_res.returncode != 0 and "nothing to commit" not in commit_res.stdout:
                return {"success": False, "error": f"git commit failed: {commit_res.stderr}"}

        # Create and switch to feature branch
        checkout_res = self._run_git(["checkout", "-B", branch_name])
        if checkout_res.returncode != 0:
            return {"success": False, "error": f"git checkout branch failed: {checkout_res.stderr}"}

        # Get latest commit hash
        rev_res = self._run_git(["rev-parse", "HEAD"])
        commit_sha = rev_res.stdout.strip()[:7] if rev_res.returncode == 0 else "unknown"

        return {
            "success": True,
            "branch": branch_name,
            "base_branch": "main",
            "commit_sha": commit_sha,
            "is_new_repo": is_new_repo,
        }

    def push_and_create_github_pr(
        self,
        token: str,
        project_name: str,
        repo_name: str,
        org: Optional[str] = None,
        branch_name: str = "feat/architectai-scaffold",
        base_branch: str = "main",
        is_private: bool = True,
        simulation_mode: bool = False,
    ) -> Dict[str, Any]:
        """
        Full end-to-end GitHub flow:
        1. Prepare local Git repository
        2. Create remote repo via GitHub API (if needed)
        3. Push feature branch and base branch
        4. Open enterprise Pull Request via GitHub API
        """
        start_time = time.perf_counter()
        clean_repo_name = re.sub(r"[^a-zA-Z0-9_\-\.]", "-", repo_name.strip()).lower()

        # Step 1: Prepare local Git repo
        local_prep = self.prepare_local_repository(project_name=project_name, branch_name=branch_name)
        if not local_prep["success"]:
            return local_prep

        pr_title = f"feat(core): autonomous architecture scaffold for {project_name.replace('_', ' ')}"
        pr_body = PRTemplateBuilder.build(
            project_name=project_name,
            project_dir=self.project_dir,
            branch_name=branch_name,
            base_branch=base_branch,
        )

        # Simulation / Sandbox mode for air-gapped demoing or missing tokens
        if simulation_mode or not token or token.strip() == "":
            elapsed_ms = round((time.perf_counter() - start_time) * 1000, 2)
            mock_owner = org or "architectai-workspace"
            mock_pr_url = f"https://github.com/{mock_owner}/{clean_repo_name}/pull/1"
            return {
                "success": True,
                "simulation": True,
                "provider": "GitHub",
                "repo_name": clean_repo_name,
                "repo_full_name": f"{mock_owner}/{clean_repo_name}",
                "repo_url": f"https://github.com/{mock_owner}/{clean_repo_name}",
                "pr_url": mock_pr_url,
                "pr_number": 1,
                "pr_title": pr_title,
                "pr_body": pr_body,
                "head_branch": branch_name,
                "base_branch": base_branch,
                "commit_sha": local_prep["commit_sha"],
                "duration_ms": elapsed_ms,
                "message": "✓ Verified Git repository staging & created simulated enterprise Pull Request (Sandbox Mode).",
            }

        headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "ArchitectAI-Platform",
        }

        # Step 2: Get user info to determine target owner
        try:
            with httpx.Client(timeout=30) as client:
                user_res = client.get("https://api.github.com/user", headers=headers)
                if user_res.status_code != 200:
                    return {
                        "success": False,
                        "error": f"GitHub Authentication failed ({user_res.status_code}): {user_res.text}",
                    }
                user_data = user_res.json()
                owner = org or user_data.get("login")
                repo_full_name = f"{owner}/{clean_repo_name}"

                # Step 3: Check if repo exists, or create it
                check_repo = client.get(f"https://api.github.com/repos/{repo_full_name}", headers=headers)
                if check_repo.status_code == 404:
                    create_url = f"https://api.github.com/orgs/{org}/repos" if org else "https://api.github.com/user/repos"
                    payload = {
                        "name": clean_repo_name,
                        "description": f"Autonomous backend service and architecture for {project_name}, generated by ArchitectAI.",
                        "private": is_private,
                        "auto_init": False,
                    }
                    create_res = client.post(create_url, headers=headers, json=payload)
                    if create_res.status_code not in (200, 201):
                        return {
                            "success": False,
                            "error": f"Failed to create GitHub repository ({create_res.status_code}): {create_res.text}",
                        }
                    repo_info = create_res.json()
                elif check_repo.status_code == 200:
                    repo_info = check_repo.json()
                else:
                    return {
                        "success": False,
                        "error": f"Error accessing GitHub repository: {check_repo.text}",
                    }

                remote_html_url = repo_info.get("html_url")

                # Step 4: Configure authenticated remote origin & push
                auth_remote_url = f"https://x-access-token:{token}@github.com/{repo_full_name}.git"
                self._run_git(["remote", "remove", "origin"])
                self._run_git(["remote", "add", "origin", auth_remote_url])

                # Push main and feature branch
                push_main = self._run_git(["push", "-u", "origin", "main", "--force"])
                push_feat = self._run_git(["push", "-u", "origin", branch_name, "--force"])

                # Remove token from remote url for security
                self._run_git(["remote", "set-url", "origin", f"https://github.com/{repo_full_name}.git"])

                if push_feat.returncode != 0 and push_main.returncode != 0:
                    return {
                        "success": False,
                        "error": f"git push failed: {push_feat.stderr or push_main.stderr}",
                    }

                # Step 5: Open Pull Request
                pr_payload = {
                    "title": pr_title,
                    "body": pr_body,
                    "head": branch_name,
                    "base": base_branch,
                }
                pr_res = client.post(
                    f"https://api.github.com/repos/{repo_full_name}/pulls",
                    headers=headers,
                    json=pr_payload,
                )

                if pr_res.status_code in (200, 210, 201):
                    pr_data = pr_res.json()
                    pr_url = pr_data.get("html_url")
                    pr_number = pr_data.get("number")
                elif pr_res.status_code == 422 and "A pull request already exists" in pr_res.text:
                    # Fetch existing PR
                    existing_prs = client.get(
                        f"https://api.github.com/repos/{repo_full_name}/pulls?head={owner}:{branch_name}",
                        headers=headers,
                    )
                    pr_data = existing_prs.json()[0] if existing_prs.status_code == 200 and existing_prs.json() else {}
                    pr_url = pr_data.get("html_url", f"https://github.com/{repo_full_name}/pulls")
                    pr_number = pr_data.get("number", 1)
                else:
                    return {
                        "success": False,
                        "error": f"Failed to create Pull Request ({pr_res.status_code}): {pr_res.text}",
                    }

                elapsed_ms = round((time.perf_counter() - start_time) * 1000, 2)
                return {
                    "success": True,
                    "simulation": False,
                    "provider": "GitHub",
                    "repo_name": clean_repo_name,
                    "repo_full_name": repo_full_name,
                    "repo_url": remote_html_url,
                    "pr_url": pr_url,
                    "pr_number": pr_number,
                    "pr_title": pr_title,
                    "pr_body": pr_body,
                    "head_branch": branch_name,
                    "base_branch": base_branch,
                    "commit_sha": local_prep["commit_sha"],
                    "duration_ms": elapsed_ms,
                    "message": f"✓ Successfully pushed branch '{branch_name}' and opened Pull Request #{pr_number}!",
                }

        except Exception as exc:
            return {
                "success": False,
                "error": f"Unexpected error during GitHub PR creation: {str(exc)}",
            }
